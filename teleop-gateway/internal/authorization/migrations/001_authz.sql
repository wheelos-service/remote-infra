CREATE TABLE IF NOT EXISTS authz_organizations (
    org_id UUID PRIMARY KEY,
    status TEXT NOT NULL CHECK (status IN ('active', 'suspended', 'disabled')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS authz_users (
    user_id UUID PRIMARY KEY,
    status TEXT NOT NULL CHECK (status IN ('active', 'suspended', 'disabled')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS authz_vehicles (
    vehicle_id TEXT PRIMARY KEY CHECK (length(vehicle_id) BETWEEN 1 AND 128),
    org_id UUID NOT NULL REFERENCES authz_organizations(org_id),
    status TEXT NOT NULL CHECK (status IN ('pending', 'active', 'suspended', 'disabled')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS authz_identity_subjects (
    issuer TEXT NOT NULL,
    subject TEXT NOT NULL,
    identity_kind TEXT NOT NULL CHECK (identity_kind IN ('user', 'vehicle')),
    PRIMARY KEY (issuer, subject),
    UNIQUE (issuer, subject, identity_kind)
);

CREATE TABLE IF NOT EXISTS authz_external_identity_bindings (
    issuer TEXT NOT NULL,
    subject TEXT NOT NULL,
    identity_kind TEXT NOT NULL DEFAULT 'user' CHECK (identity_kind = 'user'),
    user_id UUID NOT NULL REFERENCES authz_users(user_id),
    status TEXT NOT NULL CHECK (status IN ('active', 'pending', 'revoked')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (issuer, subject),
    UNIQUE (issuer, user_id),
    FOREIGN KEY (issuer, subject, identity_kind)
        REFERENCES authz_identity_subjects(issuer, subject, identity_kind)
);

CREATE TABLE IF NOT EXISTS authz_vehicle_identities (
    vehicle_id TEXT PRIMARY KEY REFERENCES authz_vehicles(vehicle_id),
    issuer TEXT NOT NULL,
    client_id TEXT NOT NULL,
    subject TEXT NOT NULL,
    identity_kind TEXT NOT NULL DEFAULT 'vehicle' CHECK (identity_kind = 'vehicle'),
    binding_version BIGINT NOT NULL CHECK (binding_version > 0),
    status TEXT NOT NULL CHECK (status IN ('pending', 'active', 'revoked')),
    secret_reference TEXT NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (issuer, client_id),
    UNIQUE (issuer, subject),
    FOREIGN KEY (issuer, subject, identity_kind)
        REFERENCES authz_identity_subjects(issuer, subject, identity_kind)
);

CREATE TABLE IF NOT EXISTS authz_organization_memberships (
    org_id UUID NOT NULL REFERENCES authz_organizations(org_id),
    user_id UUID NOT NULL REFERENCES authz_users(user_id),
    status TEXT NOT NULL CHECK (status IN ('pending', 'active', 'suspended', 'removed')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (org_id, user_id)
);

CREATE TABLE IF NOT EXISTS casbin_rule (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ptype TEXT NOT NULL CHECK (ptype IN ('p', 'g')),
    v0 TEXT NOT NULL DEFAULT '',
    v1 TEXT NOT NULL DEFAULT '',
    v2 TEXT NOT NULL DEFAULT '',
    v3 TEXT NOT NULL DEFAULT '',
    v4 TEXT NOT NULL DEFAULT '',
    v5 TEXT NOT NULL DEFAULT '',
    UNIQUE (ptype, v0, v1, v2, v3, v4, v5)
);

CREATE TABLE IF NOT EXISTS authz_authorization_state (
    state_key SMALLINT PRIMARY KEY CHECK (state_key = 1),
    version BIGINT NOT NULL CHECK (version >= 0)
);
INSERT INTO authz_authorization_state (state_key, version)
VALUES (1, 0)
ON CONFLICT (state_key) DO NOTHING;

CREATE TABLE IF NOT EXISTS authz_audit_events (
    event_id UUID PRIMARY KEY,
    org_id UUID NOT NULL REFERENCES authz_organizations(org_id),
    actor_user_id UUID NOT NULL REFERENCES authz_users(user_id),
    subject_user_id UUID REFERENCES authz_users(user_id),
    event_type TEXT NOT NULL,
    authorization_version BIGINT NOT NULL CHECK (authorization_version > 0),
    details JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS authz_outbox (
    event_id UUID PRIMARY KEY,
    org_id UUID NOT NULL REFERENCES authz_organizations(org_id),
    authorization_version BIGINT NOT NULL UNIQUE CHECK (authorization_version > 0),
    event_type TEXT NOT NULL,
    payload JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    processed_at TIMESTAMPTZ
);
